const NAME_TO_CODE: Record<string, string> = Object.entries(GST_STATE_CODES).reduce(
  (acc, [code, name]) => {
    acc[name.toLowerCase()] = code;
    return acc;
  },
  {} as Record<string, string>,
);

export function getStateName(code: string): string | undefined {
  return GST_STATE_CODES[code];
}

export function getStateCode(name: string): string | undefined {
  return NAME_TO_CODE[name.trim().toLowerCase()];
}

export function isSameState(codeA: string, codeB: string): boolean {
  return codeA === codeB;
}
